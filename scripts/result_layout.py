def plan_migration(run_dir: Path | str) -> dict[str, Any]:
    """只读生成迁移计划：绝不移动、绝不删除，冲突显式列出。"""
    root = Path(run_dir)
    layout_before = detect_layout(root)
    moves: list[dict[str, Any]] = []
    skipped: list[dict[str, str]] = []
    conflicts: list[dict[str, str]] = []
    planned_targets: set[str] = set()
    for source_rel, target_rel in _MIGRATION_TARGETS:
        source = root / source_rel
        if not source.exists():
            continue
        target = root / target_rel
        if target.exists() and source.resolve() != target.resolve():
            conflicts.append({
                "source": source_rel,
                "target": target_rel,
                "reason": "目标已存在；迁移不覆盖任何已有证据",
            })
            continue
        if target_rel in planned_targets:
            conflicts.append({
                "source": source_rel,
                "target": target_rel,
                "reason": "同一目标被多个来源占用",
            })
            continue
        planned_targets.add(target_rel)
        item: dict[str, Any] = {
            "source": source_rel,
            "target": target_rel,
            "kind": "dir" if source.is_dir() else "file",
        }
        if source.is_dir():
            files = _tree_files(source)
            item.update({
                "files": len(files),
                "bytes": sum(one["bytes"] for one in files),
                "tree_sha256": _tree_digest(files),
                "mtime": _mtime_text(source),
            })
        else:
            item.update({
                "bytes": source.stat().st_size,
                "sha256": _sha256(source),
                "mtime": _mtime_text(source),
            })
        moves.append(item)
    for name in sorted(item.name for item in root.iterdir()) if root.is_dir() else []:
        rel = name
        if any(rel == move["source"] for move in moves) or rel in ROOT_ALLOWED:
            continue
        if any(rel == conflict["source"] for conflict in conflicts):
            continue
        if any(rel.startswith(move["source"] + "/") for move in moves):
            continue
        if any(rel.startswith(conflict["source"] + "/") for conflict in conflicts):
            continue
        skipped.append({"source": rel, "reason": "未归类；保留原位，人工确认后再迁移"})
    return {
        "schema": MIGRATION_SCHEMA,
        "run_dir": str(root),
        "layout_before": layout_before,
        "layout_after": LAYOUT_V3,
        "moves": moves,
        "conflicts": conflicts,
        "skipped": skipped,
        "ok": not conflicts,
        "apply_required": bool(moves),
    }


def apply_migration(run_dir: Path | str, *, plan: Mapping[str, Any] | None = None,
                    task_id: str | None = None) -> dict[str, Any]:
    """执行迁移：逐个校验 SHA → rename → 复核 SHA，最后写迁移 manifest。

    不覆盖已有目标、不删除任何未列入计划的内容；单个失败只记录，不中断其余文件。
    """
    root = Path(run_dir)
    plan = dict(plan or plan_migration(root))
    layout_before = plan.get("layout_before") or detect_layout(root)
    applied: list[dict[str, Any]] = []
    errors: list[dict[str, str]] = []
    for move in plan.get("moves") or []:
        source = root / move["source"]
        target = root / move["target"]
        if not source.exists():
            continue
        if target.exists() and source.resolve() != target.resolve():
            errors.append({"source": move["source"], "reason": "目标已存在，拒绝覆盖"})
            continue
        try:
            if "sha256" in move and _sha256(source) != move["sha256"]:
                errors.append({"source": move["source"], "reason": "迁移前 SHA 与计划不一致"})
                continue
            target.parent.mkdir(parents=True, exist_ok=True)
            mtime_ns = source.stat().st_mtime_ns
            source.rename(target)
            os.utime(target, ns=(mtime_ns, mtime_ns), follow_symlinks=False)
            record = dict(move)
            record["mtime"] = move.get("mtime") or _mtime_text(target)
            record["mtime_after"] = _mtime_text(target)
            if move["kind"] == "dir":
                files = _tree_files(target)
                record["tree_sha256_after"] = _tree_digest(files)
                if record.get("tree_sha256") and record["tree_sha256"] != record["tree_sha256_after"]:
                    errors.append({"source": move["source"], "reason": "迁移后目录树 SHA 不一致"})
            else:
                record["sha256_after"] = _sha256(target)
                if record.get("sha256") and record["sha256"] != record["sha256_after"]:
                    errors.append({"source": move["source"], "reason": "迁移后 SHA 不一致"})
            applied.append(record)
        except OSError as error:
            errors.append({"source": move["source"], "reason": f"移动失败: {error}"})
    ensure_dirs(root, LAYOUT_V3)
    payload = {
        "schema": MIGRATION_SCHEMA,
        "generated_at": now_text(),
        "layout_before": layout_before,
        "layout_after": LAYOUT_V3,
        "applied": True,
        "moves": applied,
        "errors": errors,
        "conflicts": plan.get("conflicts") or [],
        "skipped": plan.get("skipped") or [],
    }
    manifest_dir = root / "reports"
    manifest_dir.mkdir(parents=True, exist_ok=True)
    (manifest_dir / "migration-manifest.json").write_text(
        json.dumps(payload, ensure_ascii=False, indent=2) + "\n", encoding="utf-8"
    )
    write_readme(root, task_id=task_id,
                 notes=("本目录由旧布局迁移而来；原始路径与 SHA 见 reports/migration-manifest.json。",)
                 if applied else ())
    write_manifest(root, task_id=task_id, migration=payload)
    payload["ok"] = not errors
    return payload


def migrate(run_dir: Path | str, *, apply: bool = False,
            task_id: str | None = None) -> dict[str, Any]:
    """默认 dry-run；``apply=True`` 才移动文件。"""
    plan = plan_migration(run_dir)
    if not apply:
        return plan
    return apply_migration(run_dir, plan=plan, task_id=task_id)


