def ensure_dirs(run_dir: Path | str, layout: str = LAYOUT_V3) -> dict[str, Path]:
    root = Path(run_dir)
    created: dict[str, Path] = {}
    if layout == LAYOUT_V3:
        for name in ROOT_DIRS:
            (root / name).mkdir(parents=True, exist_ok=True)
        keys = ("serial_dir", "raw_dir", "indexes_dir", "hashes_dir", "recorder_dir",
                "audio_dir", "screenshots_dir", "milestones_dir")
    elif layout == LAYOUT_TRANSITIONAL:
        keys = ("serial_dir", "raw_dir", "recorder_dir")
    else:
        keys = ("serial_dir",)
    for key in keys:
        target = path(root, key, layout)
        target.mkdir(parents=True, exist_ok=True)
        created[key] = target
    return created


