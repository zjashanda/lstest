def audit(run_dir: Path | str) -> dict[str, Any]:
    """审计根目录：列出越界项、canonical/旧布局产物和缺失项。"""
    root = Path(run_dir)
    layout = detect_layout(root)
    actual = sorted(item.name for item in root.iterdir()) if root.is_dir() else []
    violations: list[dict[str, str]] = []
    legacy: list[str] = []
    for name in actual:
        if name in ROOT_ALLOWED:
            continue
        if name in LEGACY_ROOT_FILES or name in LEGACY_ROOT_DIRS:
            legacy.append(name)
            violations.append({
                "name": name,
                "reason": "LEGACY_READABLE",
                "suggestion": _suggestion(name),
            })
        else:
            violations.append({
                "name": name,
                "reason": "UNCLASSIFIED",
                "suggestion": "人工确认归属；迁移只搬已知产物，不猜测、不删除",
            })
    present = {key: str(found.relative_to(root).as_posix())
               for key in ENTRIES
               if (found := resolve(root, key)) is not None}
    missing: list[str] = []
    if layout == LAYOUT_V3:
        for key in ("readme", "manifest", "summary_md", "events", "tool_log"):
            if key not in present:
                missing.append(ENTRIES[key].rel)
    derived = ["manifest", "tool_log", "summary_md", "summary_json", "validation"]
    return {
        "run_dir": str(root),
        "layout": layout,
        "root_entries": actual,
        "root_ok": not violations,
        "violations": violations,
        "legacy_entries": legacy,
        "present": present,
        "missing": missing,
        "derived_from_events": [ENTRIES[key].rel for key in derived],
        "canonical": {key: ENTRIES[key].rel for key in ENTRIES},
    }


def _suggestion(name: str) -> str:
    for entry in ENTRIES.values():
        if name == entry.rel or name in entry.aliases:
            return f"迁移到 {entry.rel}"
    if name == "cloud_run":
        return "迁移到 logs/legacy/cloud_run（只读兼容）"
    return "先确认归属再迁移"


