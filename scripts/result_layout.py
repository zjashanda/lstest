def _entry(key: str) -> Entry:
    try:
        return ENTRIES[key]
    except KeyError as error:
        raise KeyError(f"未知结果产物: {key}") from error


def resolve(run_dir: Path | str, key: str) -> Path | None:
    """按 canonical → 历史别名顺序找实际存在路径；都不存在返回 None。"""
    run_dir = Path(run_dir)
    entry = _entry(key)
    for rel in (entry.rel, *entry.aliases):
        candidate = run_dir / rel
        if candidate.exists():
            return candidate
    return None


def resolve_required(run_dir: Path | str, key: str) -> Path:
    found = resolve(run_dir, key)
    if found is None:
        raise FileNotFoundError(f"结果目录缺少 {key}（期望 {_entry(key).rel}）")
    return found


def normalize_reference(rel: str) -> str:
    """把旧相对引用改成 v3 canonical 相对路径（不改变文件）。"""
    base = _strip_ref_suffix(rel)
    for entry in ENTRIES.values():
        if base == entry.rel:
            return base
        if base in entry.aliases:
            return entry.rel
    for legacy, canonical in _LEGACY_PREFIX_MAP:
        if base == legacy.rstrip("/") or base.startswith(legacy):
            return canonical + base[len(legacy):]
    return base


def resolve_relative(run_dir: Path | str, rel: str) -> Path | None:
    """解析事件里的相对引用（可能带 ``#行号`` 或 ``#cursor``）。"""
    run_dir = Path(run_dir)
    base = _strip_ref_suffix(rel)
    if not base:
        return None
    candidates = [base, normalize_reference(base)]
    for entry in ENTRIES.values():
        if base == entry.rel or base in entry.aliases:
            candidates.extend([entry.rel, *entry.aliases])
    seen: set[str] = set()
    for item in candidates:
        if item in seen:
            continue
        seen.add(item)
        candidate = run_dir / item
        if candidate.exists():
            return candidate
    return None


def _strip_ref_suffix(rel: str) -> str:
    value = str(rel or "").strip().replace("\\", "/")
    if "#" in value:
        value = value.split("#", 1)[0]
    if value.startswith("./"):
        value = value[2:]
    return value


_LEGACY_PREFIX_MAP: tuple[tuple[str, str], ...] = (
    ("execution_logs/serial_logs/", "logs/serial/"),
    ("execution_logs/", "logs/"),
    ("serial_logs/", "logs/serial/"),
    ("machine/", "reports/"),
    ("raw/", "evidence/raw/"),
    ("cloud_run/", "logs/legacy/cloud_run/"),
)


def detect_layout(run_dir: Path | str) -> str:
    root = Path(run_dir)
    if not root.is_dir():
        return LAYOUT_V3
    actual = {item.name for item in root.iterdir()}
    if not actual:
        return LAYOUT_V3
    if actual & {"events", "reports", "logs", "artifacts"}:
        return LAYOUT_V3
    if actual & {"machine", "execution_logs"}:
        return LAYOUT_TRANSITIONAL
    if "events.jsonl" in actual:
        return LAYOUT_V2
    return LAYOUT_V1


