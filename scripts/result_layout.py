def write_manifest(run_dir: Path | str, *, task_id: str | None = None,
                   migration: Mapping[str, Any] | None = None,
                   extra: Mapping[str, Any] | None = None) -> Path:
    """生成根目录 manifest.json：相对路径、大小、SHA-256 与旧/新映射。"""
    root = Path(run_dir)
    root.mkdir(parents=True, exist_ok=True)
    entries: list[dict[str, Any]] = []
    for key, entry in ENTRIES.items():
        if key in {"manifest", "readme"}:
            continue
        found = resolve(root, key)
        if found is None:
            continue
        rel = found.relative_to(root).as_posix()
        item: dict[str, Any] = {
            "key": key,
            "role": entry.role,
            "kind": "dir" if found.is_dir() else "file",
            "path": rel,
            "canonical": entry.rel,
        }
        if found.is_dir():
            files = _tree_files(found)
            item["files"] = len(files)
            item["bytes"] = sum(one["bytes"] for one in files)
            item["tree_sha256"] = _tree_digest(files)
        else:
            item["bytes"] = found.stat().st_size
            item["sha256"] = _sha256(found)
        entries.append(item)
    payload: dict[str, Any] = {
        "schema": MANIFEST_SCHEMA,
        "layout": LAYOUT_V3,
        "generated_at": now_text(),
        "task_id": task_id or root.name,
        "reading_order": [name for name, _ in READING_ORDER],
        "root_allowed": {"files": list(ROOT_FILES), "dirs": list(ROOT_DIRS)},
        "entries": entries,
    }
    if extra:
        payload.update(dict(extra))
    if migration:
        payload["migration"] = {
            "schema": MIGRATION_SCHEMA,
            "moves": [{key: value for key, value in item.items() if key != "files"}
                      for item in migration.get("moves", [])],
            "conflicts": migration.get("conflicts", []),
            "skipped": migration.get("skipped", []),
            "applied": bool(migration.get("applied")),
            "layout_before": migration.get("layout_before"),
            "layout_after": migration.get("layout_after", LAYOUT_V3),
        }
    target = root / "manifest.json"
    target.write_text(json.dumps(payload, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    return target


def verify_manifest(run_dir: Path | str) -> list[dict[str, str]]:
    """核对 manifest 记录的大小/SHA 是否仍然成立。"""
    root = Path(run_dir)
    findings: list[dict[str, str]] = []
    manifest_path = root / "manifest.json"
    if not manifest_path.is_file():
        return [{"code": "MANIFEST_MISSING", "level": "ERROR", "message": "缺少 manifest.json"}]
    try:
        payload = json.loads(manifest_path.read_text(encoding="utf-8"))
    except ValueError as error:
        return [{"code": "MANIFEST_BAD", "level": "ERROR", "message": f"manifest.json 非法 JSON: {error}"}]
    for item in payload.get("entries") or []:
        target = root / str(item.get("path") or "")
        if not target.exists():
            findings.append({"code": "MANIFEST_PATH", "level": "ERROR",
                             "message": f"manifest 记录的文件缺失: {item.get('path')}"})
            continue
        if item.get("kind") == "dir":
            files = _tree_files(target)
            if item.get("tree_sha256") and _tree_digest(files) != item["tree_sha256"]:
                findings.append({"code": "MANIFEST_SHA", "level": "ERROR",
                                 "message": f"目录树 SHA 与 manifest 不一致: {item.get('path')}"})
            continue
        if item.get("bytes") is not None and target.stat().st_size != item["bytes"]:
            findings.append({"code": "MANIFEST_SIZE", "level": "ERROR",
                             "message": f"大小与 manifest 不一致: {item.get('path')}"})
        if item.get("sha256") and _sha256(target) != item["sha256"]:
            findings.append({"code": "MANIFEST_SHA", "level": "ERROR",
                             "message": f"SHA-256 与 manifest 不一致: {item.get('path')}"})
    return findings


