def _sha256(target: Path) -> str:
    import hashlib

    digest = hashlib.sha256()
    with target.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def _tree_files(root: Path) -> list[dict[str, Any]]:
    files: list[dict[str, Any]] = []
    for item in sorted(path for path in root.rglob("*") if path.is_file()):
        files.append({
            "path": item.relative_to(root).as_posix(),
            "bytes": item.stat().st_size,
            "sha256": _sha256(item),
        })
    return files


def _tree_digest(files: Sequence[Mapping[str, Any]]) -> str:
    import hashlib

    return hashlib.sha256(
        json.dumps(list(files), ensure_ascii=False, sort_keys=True).encode("utf-8")
    ).hexdigest()


def _mtime_text(target: Path) -> str:
    return datetime.fromtimestamp(target.stat().st_mtime, BEIJING).strftime(FMT_TEXT)


